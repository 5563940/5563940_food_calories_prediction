// Parse the CSV matrix into structured objects
export function parseDatabaseMatrix(csv: string): FoodItem[] {
  const lines = csv.trim().split('\n');
  const items: FoodItem[] = [];

  // Skip header line
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    let foodName = '';
    let restOfLine = '';

    if (line.startsWith('"')) {
      const closingQuoteIdx = line.indexOf('"', 1);
      if (closingQuoteIdx !== -1) {
        foodName = line.substring(1, closingQuoteIdx);
        restOfLine = line.substring(closingQuoteIdx + 2); // skip quote and comma
      }
    } else {
      const firstComma = line.indexOf(',');
      if (firstComma !== -1) {
        foodName = line.substring(0, firstComma);
        restOfLine = line.substring(firstComma + 1);
      }
    }

    if (!foodName) continue;

    const parts = restOfLine.split(',');
    const calories = parseFloat(parts[0]) || 0;
    const carbs = parts[1] !== undefined && parts[1] !== '' ? parseFloat(parts[1]) || 0 : 0;
    const protein = parts[2] !== undefined && parts[2] !== '' ? parseFloat(parts[2]) || 0 : 0;
    const fat = parts[3] !== undefined && parts[3] !== '' ? parseFloat(parts[3]) || 0 : 0;

    items.push({
      id: `food_${i}`,
      name: foodName,
      calories100g: calories,
      carbs100g: carbs,
      protein100g: protein,
      fat100g: fat,
      category: classifyCategory(foodName),
    });
  }

  return items;
}

export const FOOD_DATABASE: FoodItem[] = parseDatabaseMatrix(RAW_DATABASE_CSV);

// Quick lookup map by normalized name
export const FOOD_LOOKUP = new Map<string, FoodItem>();
FOOD_DATABASE.forEach(item => {
  FOOD_LOOKUP.set(item.name.toLowerCase().trim(), item);
});

export interface NutritionCalculation {
  foodItem: FoodItem;
  weightGrams: number;
  calories: number;
  carbs: number;
  protein: number;
  fat: number;
  formattedOutput: string;
}

/**
 * Computes nutrition strictly per system logic:
 * Final_Value = (Value_100g * User_Weight_Grams) / 100
 * Round all final calculated numbers strictly to 1 decimal place.
 * Returns exact 6-line plain text format.
 */
export function calculateNutrition(item: FoodItem, weightGrams: number): NutritionCalculation {
  const scaledCalories = Number(((item.calories100g * weightGrams) / 100).toFixed(1));
  const scaledCarbs = Number(((item.carbs100g * weightGrams) / 100).toFixed(1));
  const scaledProtein = Number(((item.protein100g * weightGrams) / 100).toFixed(1));
  const scaledFat = Number(((item.fat100g * weightGrams) / 100).toFixed(1));

  const formattedOutput = [
    `Food: ${item.name}`,
    `Weight: ${weightGrams}g`,
    `Calories: ${scaledCalories.toFixed(1)} kcal`,
    `Carbs: ${scaledCarbs.toFixed(1)}g`,
    `Protein: ${scaledProtein.toFixed(1)}g`,
    `Fat: ${scaledFat.toFixed(1)}g`,
  ].join('\n');

  return {
    foodItem: item,
    weightGrams,
    calories: scaledCalories,
    carbs: scaledCarbs,
    protein: scaledProtein,
    fat: scaledFat,
    formattedOutput,
  };
}

/**
 * Fuzzy search to match food query with database matrix
 */
export function findMatchingFood(query: string): FoodItem | null {
  if (!query) return null;
  const q = query.toLowerCase().trim();

  // 1. Exact match
  if (FOOD_LOOKUP.has(q)) {
    return FOOD_LOOKUP.get(q)!;
  }

  // 2. Exact match ignoring parenthetical botanical names
  for (const item of FOOD_DATABASE) {
    const plainName = item.name.replace(/\(.*?\)/g, '').toLowerCase().trim();
    if (plainName === q) {
      return item;
    }
  }

  // 3. Substring match
  const scored = FOOD_DATABASE.map(item => {
    const rawLower = item.name.toLowerCase();
    const cleanLower = item.name.replace(/\(.*?\)/g, '').toLowerCase().trim();
    let score = 0;

    if (cleanLower.startsWith(q)) score += 100;
    else if (rawLower.startsWith(q)) score += 80;
    else if (cleanLower.includes(q)) score += 50;
    else if (rawLower.includes(q)) score += 30;

    const words = q.split(/\s+/).filter(Boolean);
    let matchedWords = 0;
    for (const w of words) {
      if (rawLower.includes(w)) matchedWords++;
    }
    if (words.length > 0) {
      score += (matchedWords / words.length) * 40;
    }

    return { item, score };
  }).filter(res => res.score > 25);

  scored.sort((a, b) => b.score - a.score);
  return scored.length > 0 ? scored[0].item : null;
}
